#!/usr/bin/env node
/*
 * Generates docs/ROUTE_INDEX.md: every HTTP route the till server mounts, with its method, path and the access guard
 * written on the route. It reads the source (main/routes/index.ts and each router file), so it cannot drift: the
 * `--check` flag (used by tests/route-index.test.ts) fails when the committed file is out of date.
 *
 *   node scripts/generate-route-index.cjs          write docs/ROUTE_INDEX.md
 *   node scripts/generate-route-index.cjs --check  exit 1 if it is out of date
 */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const routesDir = path.join(root, 'main', 'routes');
const out = path.join(root, 'docs', 'ROUTE_INDEX.md');

const indexSrc = fs.readFileSync(path.join(routesDir, 'index.ts'), 'utf8');
const importFile = {};
for (const m of indexSrc.matchAll(/import\s*\{\s*([A-Za-z0-9_]+)\s*(?:as\s+[A-Za-z0-9_]+)?\s*\}\s*from\s*'\.\/([A-Za-z0-9_-]+)'/g)) importFile[m[1]] = m[2];
for (const m of indexSrc.matchAll(/import\s+([A-Za-z0-9_]+)\s+from\s*'\.\/([A-Za-z0-9_-]+)'/g)) importFile[m[1]] = m[2];

const mounts = [];
for (const m of indexSrc.matchAll(/app\.use\('(\/api\/[^']*)',\s*([A-Za-z0-9_]+)\)/g)) mounts.push({ prefix: m[1], file: importFile[m[2]], name: m[2] });

function guardOf(text) {
  const g = [];
  const role = text.match(/requireRole\(([^)]*)\)/); if (role) g.push('role: ' + role[1].replace(/['"\s]/g, '').replace(/,/g, ', '));
  const perm = text.match(/requirePermission\('([^']+)'/); if (perm) g.push('permission: ' + perm[1]);
  const feat = text.match(/requireFeature\('([^']+)'/); if (feat) g.push('feature: ' + feat[1]);
  if (/requireAuth/.test(text) && !g.length) g.push('signed in');
  return g.join('; ') || 'see handler';
}

function routesIn(file) {
  const src = fs.readFileSync(path.join(routesDir, file + '.ts'), 'utf8');
  const found = [];
  // Guards bound to a name once and reused: const till = requireRole('owner', ...);
  const named = {};
  for (const d of src.matchAll(/const\s+([A-Za-z0-9_]+)\s*=\s*(require(?:Role|Permission|Feature)\([^;]*\));/g)) named[d[1]] = d[2];
  const re = /router\.(get|post|put|patch|delete)\(\s*(['"`])([^'"`]*)\2([\s\S]*?)(?=\n(?:router\.|export|\/\/ |\/\*|const |function |async function )|$)/g;
  let m;
  while ((m = re.exec(src))) {
    let head = m[4].split(/\(req[,:)]|\(_req|async \(|\(request/)[0];
    for (const [name, def] of Object.entries(named)) if (new RegExp('\\b' + name + '\\b').test(head)) head += ' ' + def;
    found.push({ method: m[1].toUpperCase(), sub: m[3] === '/' ? '' : m[3], guard: guardOf(head) });
  }
  return found;
}

const rows = [];
for (const mt of mounts) {
  if (!mt.file) continue;
  let list;
  try { list = routesIn(mt.file); } catch { continue; }
  for (const r of list) rows.push({ method: r.method, path: mt.prefix + r.sub, guard: r.guard, file: `main/routes/${mt.file}.ts` });
}
// Routes registered directly on the app in index.ts / server.ts.
for (const [fileLabel, src] of [['main/routes/index.ts', indexSrc], ['main/server.ts', fs.readFileSync(path.join(root, 'main', 'server.ts'), 'utf8')]]) {
  for (const m of src.matchAll(/app\.(get|post|put|patch|delete)\('(\/api\/[^']*)'([^\n]*)/g)) {
    if (/requireTradingLicence\);$/.test(m[3].trim())) continue; // a gate on a route defined elsewhere
    rows.push({ method: m[1].toUpperCase(), path: m[2], guard: guardOf(m[3]) === 'see handler' ? (m[2] === '/api/health' || m[2] === '/api/brand' ? 'public' : 'see handler') : guardOf(m[3]), file: fileLabel });
  }
}
rows.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));

const gated = ['/api/orders', '/api/orders/:id/items', '/api/bills/generate', '/api/bills/:id/payment', '/api/bills/:id/payments', '/api/card/attempts', '/api/retail/checkout'];
let md = `# Route index

Generated by \`node scripts/generate-route-index.cjs\` from the source. Do not edit by hand; \`npm run test:route-index\`
fails when this file is out of date. Narrative documentation for the main surfaces is in \`docs/API.md\`; this index is the
complete list.

- **Guard** is what is written on the route (\`requireRole\`, \`requirePermission\`, \`requireFeature\`). Routes marked
  *see handler* check access inside the handler or inherit it from the router.
- **Trading gate:** \`POST\` to ${gated.map((g) => '`' + g + '`').join(', ')} also returns **402 \`license_blocked\`** when the
  licence does not allow trading. Reading, reports, refunds and backups are never gated.
- **Base URL** \`http://<till>:3001\`. Authentication is a bearer token from \`POST /api/auth/login\`.

| Method | Path | Guard | Source |
| --- | --- | --- | --- |
`;
for (const r of rows) md += `| ${r.method} | \`${r.path}\` | ${r.guard} | \`${r.file}\` |\n`;
md += `\n${rows.length} routes.\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== md) { console.error('docs/ROUTE_INDEX.md is out of date. Run: node scripts/generate-route-index.cjs'); process.exit(1); }
  console.log(`docs/ROUTE_INDEX.md is current (${rows.length} routes)`);
} else {
  fs.writeFileSync(out, md);
  console.log(`Wrote docs/ROUTE_INDEX.md (${rows.length} routes)`);
}
module.exports = { rows };
